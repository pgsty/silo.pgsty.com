#!/usr/bin/env python3
"""Contract tests: run with the same Python/boto3 environment as the audit tool."""
import datetime
import importlib.util
import io
import json
import pathlib
import sys
import unittest
from unittest.mock import patch

import boto3
from botocore.stub import Stubber

tool = pathlib.Path(__file__).resolve().parents[1] / "static/tools/replica-metadata-audit.py"
sys.dont_write_bytecode = True  # Keep generated bytecode out of the published static tree.
spec = importlib.util.spec_from_file_location("replica_audit", tool)
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)
NOW = datetime.datetime(2026, 9, 16, tzinfo=datetime.timezone.utc)


def version(key="path/old version", vid="old", latest=False):
    return {"Key": key, "VersionId": vid, "IsLatest": latest, "LastModified": NOW,
            "ETag": '"etag"', "Size": 42}


def head(vid="old", encoding="gzip, aws-chunked", **extra):
    return {"VersionId": vid, "ContentEncoding": encoding, "ETag": '"etag"',
            "ContentLength": 42, "LastModified": NOW, **extra}


class InventoryTests(unittest.TestCase):
    def setUp(self):
        self.client = boto3.client("s3", endpoint_url="http://127.0.0.1:1", region_name="us-east-1",
                                   aws_access_key_id="fixture", aws_secret_access_key="fixture-secret")
        self.stub = Stubber(self.client)
        self.stub.activate()
        self.addCleanup(self.stub.deactivate)

    def test_tokens_do_not_confuse_substrings_or_ambiguous_values(self):
        cases = [(None, "unaffected-header", None), ("gzip", "unaffected-header", None),
                 ("my-aws-chunked", "unaffected-header", None),
                 ("aws-chunked", "confirmed-header", None),
                 ("gzip, aws-chunked, br", "confirmed-header", "gzip, br"),
                 ("AWS-CHUNKED", "ambiguous", None),
                 ("aws-chunked, aws-chunked", "ambiguous", None),
                 ("gzip,,aws-chunked", "ambiguous", None), ("", "ambiguous", None)]
        for raw, state, proposed in cases:
            with self.subTest(raw=raw):
                self.assertEqual(audit.classify(raw)[:2], (state, proposed))

    def test_pagination_preserves_noncurrent_identity_and_markers(self):
        key = "目录/spaces %2F +\nobject"
        self.stub.add_response("list_object_versions", {
            "IsTruncated": True, "NextKeyMarker": key, "NextVersionIdMarker": "new",
            "Versions": [version(key, "new", True)]}, {"Bucket": "bucket", "Prefix": ""})
        self.stub.add_response("head_object", head("new", "gzip"),
                               {"Bucket": "bucket", "Key": key, "VersionId": "new"})
        self.stub.add_response("list_object_versions", {
            "IsTruncated": False, "Versions": [version(key)],
            "DeleteMarkers": [{"Key": "deleted", "VersionId": "marker", "IsLatest": True, "LastModified": NOW}]},
            {"Bucket": "bucket", "Prefix": "", "KeyMarker": key, "VersionIdMarker": "new"})
        self.stub.add_response("head_object", head(Metadata={"private-field": "must-not-export"}),
                               {"Bucket": "bucket", "Key": key, "VersionId": "old"})
        rows = list(audit.inventory(self.client, "bucket", "", "fixture-site"))
        self.assertEqual([r["classification"] for r in rows],
                         ["unaffected-header", "delete-marker", "confirmed-header"])
        self.assertEqual(rows[2]["key"], key)
        self.assertFalse(rows[2]["is_latest_at_listing"])
        self.assertEqual(rows[2]["proposed_content_encoding"], "gzip")
        self.assertNotIn("must-not-export", str(rows))
        self.stub.assert_no_pending_responses()

    def test_denied_head_and_concurrent_state_change_are_ambiguous(self):
        self.stub.add_response("list_object_versions", {"IsTruncated": False,
            "Versions": [version("denied"), version("changed"), version("wrong-version")]},
            {"Bucket": "bucket", "Prefix": ""})
        self.stub.add_client_error("head_object", "AccessDenied", "sensitive error detail", 403,
                                  expected_params={"Bucket": "bucket", "Key": "denied", "VersionId": "old"})
        self.stub.add_response("head_object", head(ContentLength=43),
                               {"Bucket": "bucket", "Key": "changed", "VersionId": "old"})
        self.stub.add_response("head_object", head("different"),
                               {"Bucket": "bucket", "Key": "wrong-version", "VersionId": "old"})
        rows = list(audit.inventory(self.client, "bucket", "", "fixture-site"))
        self.assertTrue(all(r["classification"] == "ambiguous" for r in rows))
        self.assertNotIn("sensitive error detail", str(rows))
        self.stub.assert_no_pending_responses()

    def test_null_version_without_response_header_is_supported(self):
        listed = version("plain", "null", True)
        listed["LastModified"] = NOW.replace(microsecond=123000)
        self.stub.add_response("list_object_versions", {"IsTruncated": False,
            "Versions": [listed]}, {"Bucket": "bucket", "Prefix": ""})
        response = head()
        response.pop("VersionId")
        response.pop("ContentEncoding")
        self.stub.add_response("head_object", response,
                               {"Bucket": "bucket", "Key": "plain", "VersionId": "null"})
        rows = list(audit.inventory(self.client, "bucket", "", "fixture-site"))
        self.assertEqual(rows[0]["classification"], "unaffected-header")
        self.stub.assert_no_pending_responses()

    def run_main(self):
        output = io.StringIO()
        with patch.object(boto3, "Session") as session, patch("sys.stdout", output), patch("sys.argv", [
                "audit", "--endpoint-url", "http://127.0.0.1:1", "--bucket", "bucket", "--site", "fixture"]):
            session.return_value.client.return_value = self.client
            code = audit.main()
        return code, [json.loads(line) for line in output.getvalue().splitlines()]

    def test_partial_listing_cannot_report_complete(self):
        self.stub.add_response("list_object_versions", {"IsTruncated": True,
            "NextKeyMarker": "path/old version", "NextVersionIdMarker": "old",
            "Versions": [version()]}, {"Bucket": "bucket", "Prefix": ""})
        self.stub.add_response("head_object", head(),
                               {"Bucket": "bucket", "Key": "path/old version", "VersionId": "old"})
        self.stub.add_client_error("list_object_versions", "AccessDenied", "private", 403,
            expected_params={"Bucket": "bucket", "Prefix": "", "KeyMarker": "path/old version", "VersionIdMarker": "old"})
        code, rows = self.run_main()
        self.assertEqual(code, 1)
        self.assertFalse(rows[-1]["listing_complete"])
        self.assertEqual(rows[-1]["counts"]["confirmed-header"], 1)
        self.stub.assert_no_pending_responses()

    def test_complete_listing_with_unreadable_version_returns_two(self):
        self.stub.add_response("list_object_versions", {"IsTruncated": False, "Versions": [version()]},
                               {"Bucket": "bucket", "Prefix": ""})
        self.stub.add_client_error("head_object", "AccessDenied", "private", 403,
            expected_params={"Bucket": "bucket", "Key": "path/old version", "VersionId": "old"})
        code, rows = self.run_main()
        self.assertEqual(code, 2)
        self.assertTrue(rows[-1]["listing_complete"])
        self.assertEqual(rows[-1]["counts"]["ambiguous"], 1)
        self.stub.assert_no_pending_responses()


if __name__ == "__main__":
    unittest.main()
